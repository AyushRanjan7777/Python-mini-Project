# MOVIE RATING ANALYZER
# Python + Pandas + NumPy

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# Get movie details from user
names = []
genres = []
ratings = []

n = int(input("Enter number of movies: "))

for i in range(n):
    print("\nMovie", i + 1)

    name = input("Enter movie name: ")
    genre = input("Enter genre: ")
    rating = float(input("Enter rating (0-10): "))

    if rating < 0 or rating > 10:
        print("Invalid rating! Enter between 0 and 10.")
        rating = float(input("Enter rating again: "))

    names.append(name)
    genres.append(genre)
    ratings.append(rating)

# Create DataFrame
data = {
    "Movie": names,
    "Genre": genres,
    "Rating": ratings
}

df = pd.DataFrame(data)

# Display movie details
print("\nMOVIE DETAILS")
print(df)

# Calculate statistics
print("\nTotal Movies:", len(df))
print("Average Rating:", np.mean(df["Rating"]))
print("Highest Rating:", np.max(df["Rating"]))
print("Lowest Rating:", np.min(df["Rating"]))

# Find best and lowest movies
best = df.loc[df["Rating"].idxmax()]
worst = df.loc[df["Rating"].idxmin()]

print("\nBest Movie:", best["Movie"])
print("Lowest Rated Movie:", worst["Movie"])

# Rank movies
ranking = df.sort_values(
    by="Rating", ascending=False
)

print("\nMOVIE RANKING")
print(ranking)

# Display graph
plt.bar(df["Movie"], df["Rating"])
plt.title("Movie Rating Analysis")
plt.xlabel("Movies")
plt.ylabel("Rating")
plt.ylim(0, 10)
plt.xticks(rotation=30)
plt.show()

# Save report
df.to_csv("movie_rating_report.csv", index=False)

print("\nAnalysis Completed!")